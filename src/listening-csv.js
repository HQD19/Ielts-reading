function csvAnswerEntries() {
  const entries = [];
  for (const row of CAMBRIDGE20_CSV) {
    for (const item of row.Answers.split('|')) {
      const match = item.trim().match(/^(\d+)(?:-(\d+))?\.\s*(.+)$/);
      if (!match) continue;
      const first = Number(match[1]), last = Number(match[2] || match[1]);
      const raw = match[3];
      const pair = raw.match(/^([A-E]),\s*([A-E])\b/);
      for (let n = first; n <= last; n++) {
        const manualReference = n >= 25 && n <= 30;
        let answer = pair ? pair[n-first+1] : raw;
        let accept = [];
        if (!manualReference) {
          answer = answer.replace(/\s*\([^)]*\)/g, '').trim();
          accept = answer.split('/').map(a => a.trim());
          if (n === 9) accept.push('local products', 'local');
          if (n === 38) accept.push('ferries');
          if (n === 40) accept.push('drones');
        }
        entries.push({n, answer, accept, manualReference});
      }
    }
  }
  return entries;
}

function applyCambridge20Csv(tests) {
  const test = tests.find(t => t.book === 20 && t.sourceTest === 1);
  if (!test) return;
  const part3Answers = ['C','E','D','E','B','B','B','B','B','A'].map((answer,i) => ({n:21+i, answer, accept:[answer]}));
  test.id = 'c20l1-full-csv';
  test.csvSource = true;
  test.part3Revision = 'supplied-v1';
  test.sourceNote = '';
  test.groups = [{questions:[21,22],answers:['C','E']},{questions:[23,24],answers:['D','E']}];
  test.answers = csvAnswerEntries().filter(q => q.n < 21 || q.n > 30)
    .concat(part3Answers).sort((a,b) => a.n-b.n);
}

function csvBlankText(text) {
  return esc(text).replace(/(?:Q)?(\d{1,2})\s*\[[^\]]+\]/g,
    (_, n) => '<span class="exam-blank"><b>'+n+'</b><span aria-label="Answer '+n+'">________________</span></span>')
    .replace(/\s*\[[^\]]+\]/g, '');
}

function renderCambridge20Csv(test, selectedPart) {
  if (selectedPart === 3) {
    return '<section class="listening-text exam-content"><div class="exam-heading"><span class="exam-kicker">PART 3 · QUESTIONS 21–30</span><h2>Loneliness and mental health</h2><p>Questions 21–24: choose TWO letters for each pair. Questions 25–30: choose A, B or C.</p></div>' +
      CAMBRIDGE20_PART3.map(q => '<div class="exam-question">'+(q.instruction?'<p class="group-instruction">'+esc(q.instruction)+'</p>':'')+
        '<div class="exam-prompt"><span class="exam-q-number">'+q.numbers+'</span><p>'+esc(q.prompt)+'</p></div><div class="exam-choices">'+
        q.options.map((option,i) => '<div><b>'+'ABCDE'[i]+'</b><span>'+esc(option)+'</span></div>').join('')+'</div></div>').join('')+'</section>';
  }
  const row = CAMBRIDGE20_CSV[selectedPart-1];
  const lines = row.Exact_Question_Content.split(/\r?\n/).map(s => s.trim()).filter(Boolean);
  const titles = ['Restaurant recommendations','Adelman Pottery','Loneliness and mental health','The role of rivers in cities'];
  const instructions = ['Complete the table. Write ONE WORD AND/OR A NUMBER for each answer.',
    'Questions 11–16: Choose A, B or C. Questions 17–20: Match each statement to the equipment.',
    'Read each question carefully. For Questions 21–22, choose TWO letters.',
    'Complete the notes. Write ONE WORD ONLY for each answer.'];
  let html = '<div class="exam-heading"><span class="exam-kicker">PART '+selectedPart+' · QUESTIONS '+(selectedPart*10-9)+'–'+selectedPart*10+'</span><h2>'+titles[selectedPart-1]+'</h2><p>'+instructions[selectedPart-1]+'</p></div>';
  if (selectedPart === 1) {
    html += '<div class="exam-table-wrap"><table class="exam-table"><thead><tr><th>Restaurant</th><th>Location</th><th>Reason for recommendation</th><th>Other comments</th></tr></thead><tbody>';
    for (const line of lines.filter(l => l.startsWith('•'))) {
      html += '<tr>'+line.replace(/^•\s*/, '').split('|').map(cell => '<td>'+csvBlankText(cell.replace(/^(Location|Reason for recommendation|Other comments):\s*/, ''))+'</td>').join('')+'</tr>';
    }
    html += '</tbody></table></div>';
  } else {
    for (const line of lines) {
      if (!line.startsWith('•')) {
        if (selectedPart === 4 && line === lines[0]) continue;
        html += '<h3 class="exam-group">'+esc(line.replace(/:$/, ''))+'</h3>';
        continue;
      }
      const clean = line.replace(/^•\s*/, '').replace(/\s*\[[^\]]+\]/g, '');
      const number = clean.match(/^Q(\d+(?:-\d+)?)\.?\s*/);
      if (number) {
        const text = clean.slice(number[0].length);
        const choiceAt = text.search(/\bA\)/);
        const prompt = choiceAt < 0 ? text : text.slice(0,choiceAt);
        const choices = choiceAt < 0 ? [] : [...text.slice(choiceAt).matchAll(/([A-E])\)\s*(.*?)(?=\s*\|\s*[A-E]\)|$)/g)];
        html += '<div class="exam-question"><div class="exam-prompt"><span class="exam-q-number">'+esc(number[1])+'</span><p>'+esc(prompt)+'</p></div>';
        html += choices.length ? '<div class="exam-choices">'+choices.map(m=>'<div><b>'+m[1]+'</b><span>'+esc(m[2].replace(/\s*\|\s*$/, ''))+'</span></div>').join('')+'</div>' : '';
        html += '</div>';
      } else {
        html += '<p class="exam-note">'+csvBlankText(line.replace(/^•\s*/, ''))+'</p>';
      }
    }
  }
  return '<section class="listening-text exam-content">'+html+'</section>';
}
